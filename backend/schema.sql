
-- admins table
CREATE TABLE IF NOT EXISTS admins (
    id SERIAL PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    hashed_password VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'admin',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- api_groups table
CREATE TABLE IF NOT EXISTS api_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  apis INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- api_subgroups table
CREATE TABLE IF NOT EXISTS api_subgroups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT REFERENCES api_groups(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- users table (Safe creation without deleting data)
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  company_name TEXT,
  company_website TEXT,
  company_address TEXT,
  pan_number TEXT,
  mobile_number TEXT,
  password TEXT NOT NULL,
  status TEXT DEFAULT 'Pending', 
  otp TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- Ensure columns exist if table was already created previously
ALTER TABLE users ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'Pending';
ALTER TABLE users ADD COLUMN IF NOT EXISTS otp TEXT;


-- Create products_apis table using TEXT for all string fields
CREATE TABLE IF NOT EXISTS products_apis (
    id SERIAL PRIMARY KEY,
    menu_name TEXT,
    api_name TEXT NOT NULL,
    select_group TEXT NOT NULL,
    select_sub_group TEXT NOT NULL,
    method TEXT NOT NULL,
    request_url TEXT NOT NULL,
    target_url TEXT NOT NULL,
    request_body TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);